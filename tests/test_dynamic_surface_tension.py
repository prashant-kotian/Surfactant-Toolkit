"""Tests for surfactantkit.dynamic_surface_tension -- built 2026-09-25.

No real raw (surface_age, gamma) dataset was available during this
module's literature research pass (only a real paper's FITTED-PARAMETER
summary table, Ritacco/Langevin/Diamant/Andelman arXiv:1008.1230v2, whose
own sign convention for Delta_gamma differs from this module's -- see the
module's own docstring). Exact-recovery-on-synthetic-data is therefore the
honest validation route here (the same discipline this project already
uses when raw literature data isn't directly available), not a literal
reproduction of the paper's own numbers -- the model FORMS themselves
(DLA, KLA, Rosen-Hua) are real and cited; what's tested here is that this
module's own fitting code correctly recovers known-true parameters from
data generated by its own documented equations.
"""
import math
import pytest

from surfactantkit.dynamic_surface_tension import (
    fit_dla_regime, fit_kla_regime, select_dst_kinetic_regime, fit_rosen_hua,
)


def test_fit_dla_regime_exact_recovery():
    gamma0 = 72.0
    tau_d_true, dg_eq_true = 0.005, 15.0
    ts = [0.02, 0.05, 0.1, 0.2, 0.5, 1.0, 2.0, 5.0, 10.0]
    gammas = [gamma0 - dg_eq_true * (1 - math.sqrt(tau_d_true / t)) for t in ts]
    r = fit_dla_regime(ts, gammas, gamma0)
    assert r.tau_d_s == pytest.approx(tau_d_true, rel=1e-3)
    assert r.delta_gamma_eq_mN_m == pytest.approx(dg_eq_true, rel=1e-3)
    assert r.r_squared > 0.999


def test_fit_dla_regime_derives_diffusion_coefficient_only_when_isotherm_params_given():
    gamma0 = 72.0
    tau_d_true, dg_eq_true = 0.005, 15.0
    ts = [0.02, 0.05, 0.1, 0.2, 0.5, 1.0, 2.0, 5.0, 10.0]
    gammas = [gamma0 - dg_eq_true * (1 - math.sqrt(tau_d_true / t)) for t in ts]

    r_no_isotherm = fit_dla_regime(ts, gammas, gamma0)
    assert r_no_isotherm.diffusion_coefficient_m2_per_s is None
    assert r_no_isotherm.gap is not None and "tau_d" in r_no_isotherm.gap

    r_with_isotherm = fit_dla_regime(ts, gammas, gamma0, theta_0_eq=0.9, beta_a_per_mM=2.0, a_molecular_size_m=5e-10)
    assert r_with_isotherm.diffusion_coefficient_m2_per_s is not None
    assert r_with_isotherm.diffusion_coefficient_m2_per_s > 0
    assert r_with_isotherm.gap is None
    # D = a^2 / (beta_a^2 * tau_d), exact closed-form check against the same fitted tau_d
    expected_D = (5e-10 ** 2) / ((2.0 ** 2) * r_with_isotherm.tau_d_s)
    assert r_with_isotherm.diffusion_coefficient_m2_per_s == pytest.approx(expected_D, rel=1e-9)


def test_fit_kla_regime_exact_recovery():
    tau_k_true, amplitude_true, eq = 3.0, 1.0, 0.0
    ts = [0.1, 0.3, 1.0, 3.0, 10.0, 30.0]
    # gamma0 - gamma(t) = eq - amplitude*exp(-t/tau_k), decaying toward eq from below
    gammas = [0.0 - (eq - amplitude_true * math.exp(-t / tau_k_true)) for t in ts]
    r = fit_kla_regime(ts, gammas, gamma0_mN_m=0.0, delta_gamma_eq_mN_m=eq)
    assert r.tau_k_s == pytest.approx(tau_k_true, rel=1e-6)
    assert r.amplitude_mN_m == pytest.approx(amplitude_true, rel=1e-6)
    assert r.r_squared > 0.999
    assert r.n_points_excluded == 0


def test_fit_kla_regime_raises_on_no_decaying_signal():
    # Flat data -- no genuine relaxation to fit.
    ts = [0.1, 0.3, 1.0, 3.0, 10.0]
    gammas = [50.0, 50.0, 50.0, 50.0, 50.0]
    with pytest.raises(ValueError):
        fit_kla_regime(ts, gammas, gamma0_mN_m=0.0, delta_gamma_eq_mN_m=100.0)


def test_select_dst_kinetic_regime_detects_real_kla_signal():
    gamma0 = 72.0
    ts = [0.0005 * (1.6 ** i) for i in range(20)]
    tau_d_true, dg_eq_true, tau_k_true, amp_true = 0.0005, 15.0, 3.0, 1.0
    gammas = [
        gamma0 - (dg_eq_true * (1 - math.sqrt(tau_d_true / t)) - amp_true * math.exp(-t / tau_k_true))
        for t in ts
    ]
    result = select_dst_kinetic_regime(ts, gammas, gamma0)
    assert result.selected_regime == "dla_plus_kla"
    assert result.kla_fit is not None
    assert result.delta_bic is not None and result.delta_bic > 0
    # tau_k should genuinely exceed tau_d in the winning fit -- the real,
    # physically-required ordering this function enforces during its search.
    assert result.kla_fit.tau_k_s > result.dla_fit.tau_d_s


def test_select_dst_kinetic_regime_reports_standalone_dla_fit_not_joint_cofit():
    # Real regression guard, found 2026-09-27 via a real cross-check on real
    # senior's-thesis GZ-69 data (10-3-10 gemini, "at cmc"): an earlier bug
    # substituted the JOINT fit's own co-fit tau_d/Delta_gamma_eq into the
    # returned dla_fit when reporting dla_plus_kla, with the COMBINED
    # 4-parameter model's r_squared misleadingly attached to it (as if it
    # were a standalone DLA fit's own r_squared -- confirmed wrong via an
    # independent from-scratch brute-force 2D grid search). dla_fit must
    # always equal what fit_dla_regime itself returns standalone.
    gamma0 = 72.0
    t = [0.07, 0.09, 0.19, 0.22, 0.50, 0.72, 0.75, 0.82, 0.85, 0.98,
         1.07, 1.47, 1.58, 2.88, 2.88, 3.10, 3.38, 4.13]
    g = [60.0, 60.0, 58.5, 57.0, 56.0, 55.0, 54.5, 53.3, 52.5, 52.5,
         51.8, 51.8, 51.0, 50.7, 50.2, 49.7, 49.5, 48.9]
    standalone = fit_dla_regime(t, g, gamma0)
    result = select_dst_kinetic_regime(t, g, gamma0)
    assert result.selected_regime == "dla_plus_kla"
    assert result.dla_fit.tau_d_s == pytest.approx(standalone.tau_d_s, rel=1e-9)
    assert result.dla_fit.delta_gamma_eq_mN_m == pytest.approx(standalone.delta_gamma_eq_mN_m, rel=1e-9)
    assert result.dla_fit.r_squared == pytest.approx(standalone.r_squared, rel=1e-9)
    # The real, independently-verified standalone DLA-only fit for this data:
    # a modest r_squared (~0.88), NOT the high r_squared (~0.97) that belongs
    # to the accepted combined model -- the two must not be conflated.
    assert result.dla_fit.r_squared < 0.9
    assert result.dla_fit.r_squared > 0.8


def test_select_dst_kinetic_regime_stays_dla_only_for_pure_dla_data():
    gamma0 = 72.0
    ts = [0.0005 * (1.6 ** i) for i in range(20)]
